enum CactusPixels<'a> {
    Cactus0(&'a [usize]),
    Cactus1(&'a [usize]),
    Cactus2(&'a [usize]),
}

pub struct Cactus<'a> {
    top: i32,
    left: i32,
    width: usize,
    height: usize,
    begin: bool,
    id: usize,
    scale: usize,
    x_speed: i32,
    pixel: CactusPixels<'a>,
}

impl <'a> Cactus<'a> {
    pub fn new(scale: usize, x_speed: i32) -> Self {
        let id = (rand() % 3) as usize;
        let left = SCREEN_WIDTH;

        let (original_width, original_height, pixel) = match id {
            0 => (WIDTH_0, HEIGHT_0, CactusPixels::Cactus0(&CACTUS_0)),
            1 => (WIDTH_1, HEIGHT_1, CactusPixels::Cactus1(&CACTUS_1)),
            2 => (WIDTH_2, HEIGHT_2, CactusPixels::Cactus2(&CACTUS_2)),
            _ => unreachable!()
        };

        Cactus {
            id,
            scale,
            x_speed,
            left: left as i32,
            width: original_width * scale,
            height: original_height * scale,
            begin: false,
            top: (GROUND_HEIGHT - original_height * scale) as i32,
            pixel,
        }
    }

    pub fn outofbound(&self) -> bool {
        self.left + (self.width as i32) < 0
    }
}

impl<'a> Entity for Cactus<'a> {
    fn get_top(&self) -> i32 {
        self.top
    }

    fn get_height(&self) -> usize {
        self.height
    }

    fn get_left(&self) -> i32 {
        self.left
    }

    fn get_width(&self) -> usize {
        self.width
    }

    fn start(&mut self) {
        self.begin = true;
    }

    fn reset(&mut self) {
        self.id = (rand() % 3) as usize;
        self.begin = false;

        let (original_width, original_height, pixel) = match self.id {
            0 => (WIDTH_0, HEIGHT_0, CactusPixels::Cactus0(&CACTUS_0)),
            1 => (WIDTH_1, HEIGHT_1, CactusPixels::Cactus1(&CACTUS_1)),
            2 => (WIDTH_2, HEIGHT_2, CactusPixels::Cactus2(&CACTUS_2)),
            _ => unreachable!()
        };

        self.width = original_width * self.scale;
        self.height = original_height * self.scale;
        self.top = (GROUND_HEIGHT - self.height) as i32;
        self.left = SCREEN_WIDTH as i32;
        self.pixel = pixel;
    }

    fn update(&mut self, frame_buffer: &mut [u32]) {
        if !self.begin {
            return;
        }

        self.left -= self.x_speed;
        if self.left + (self.width as i32) < 0 || self.left > SCREEN_WIDTH as i32 {
            return;
        }

        let (original_width, original_height, pixel) = match self.pixel {
            CactusPixels::Cactus0(pixels) => (WIDTH_0 as i32, HEIGHT_0 as i32, pixels),
            CactusPixels::Cactus1(pixels) => (WIDTH_1 as i32, HEIGHT_1 as i32, pixels),
            CactusPixels::Cactus2(pixels) => (WIDTH_2 as i32, HEIGHT_2 as i32, pixels),
        };

        for i in 0..original_height {
            for j in 0..original_width {
                let color = pixel[(i * original_width + j) as usize];
                for dy in 0..self.scale {
                    for dx in 0..self.scale {
                        let x = self.left  + j * self.scale as i32 + dx as i32;
                        let y = self.top + i * self.scale as i32 + dy as i32;
                        if x >= 0 && x < SCREEN_WIDTH as i32 && y >= 0 && y < SCREEN_HEIGHT as i32 {
                            let address: usize = (y as usize * SCREEN_WIDTH + x as usize) as usize;
                            write_to_vga(address, color, frame_buffer);
                        }
                    }
                }
            }
        }

    }
}