impl<'a> Trex<'a> {
    pub fn new(scale: usize, y_speed: i32) -> Self {
        Trex {
            height: TREX_HEIGHT * scale,
            width: TREX_WIDTH * scale,
            y_speed,
            velocity_y: 0,
            scale,
            top: (GROUND_HEIGHT - TREX_HEIGHT * scale) as i32,
            left: TREX_X_POS,
            initial_y: (GROUND_HEIGHT - TREX_HEIGHT * scale) as i32,
            frame_id: 0,
            status: Status::Halting,
            pixels: &TREX_PIXELS
        }
    }

    pub fn jump(&mut self) {
        if self.status == Status::Running {
            self.status = Status::Jumping;
            self.velocity_y -= self.y_speed;  // BUG it should be a value, instead of a number
        }
    }

    pub fn crashed(&self, other: &impl Entity) -> bool {
        let self_right = self.left + self.width as i32;
        let self_bottom = self.top + self.height as i32;
        let other_right = other.get_left() + other.get_width() as i32;
        let other_bottom = other.get_top() + other.get_height() as i32;

        self.left < other_right && self_right > other.get_left() && self.top < other_bottom && self_bottom > other.get_top()
    }
}

impl<'a> Entity for Trex<'a> {
    fn get_top(&self) -> i32 {
        self.top
    }

    fn get_height(&self) -> usize {
        self.height
    }

    fn get_left(&self) -> i32 {
        self.left
    }

    fn get_width(&self) -> usize {
        self.width
    }

    fn start(&mut self) {
        self.status = Status::Running;
    }

    fn reset(&mut self) {
        self.top = self.initial_y;
        self.status = Status::Halting;
    }

    fn update(&mut self, frame_buffer: &mut [u32]) {
        match self.status {
            Status::Running => {
                self.frame_id = (self.frame_id + 1) % 3;
            }
            Status::Jumping => {
                self.top += self.velocity_y;
                self.velocity_y += GRAVITY;
                if self.top >= self.initial_y {
                    self.top = self.initial_y;
                    self.status = Status::Running;
                }
            }
            Status::Halting => {
                self.frame_id = 0;
            }
        }
        
        for i in 0..TREX_HEIGHT {
            for j in 0..TREX_WIDTH {
                let color = self.pixels[self.frame_id][i * TREX_WIDTH + j];
                for dy in 0..self.scale as usize {
                    for dx in 0..self.scale as usize {
                        let address: usize = (self.top as usize + i * self.scale as usize + dy) * SCREEN_WIDTH as usize + (self.left as usize + j * self.scale as usize + dx);
                        write_to_vga(address, color, frame_buffer);
                    }
                }
            }
        }
    }
}